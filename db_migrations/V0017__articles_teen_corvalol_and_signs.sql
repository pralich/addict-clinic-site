## Что можно найти дома

Обращайте внимание на необычные находки в комнате, рюкзаке, карманах:

- пустые флаконы из-под капель — корвалол, валокордин, другие успокоительные — и банки энергетиков в большом количестве
- блистеры от таблеток, которые вы не покупали, или пропажа лекарств из домашней аптечки
- маленькие пакетики с застёжкой, свёрнутые купюры, фольга, обрезанные трубочки
- самодельные курительные приспособления, вейпы, жидкости непонятного происхождения
- глазные капли от покраснения — их могут использовать, чтобы скрыть признаки

:::callout warning
Проверьте домашнюю аптечку. Подростки нередко берут успокоительные, снотворные и обезболивающие у взрослых. Препараты с фенобарбиталом, транквилизаторы и сильные обезболивающие лучше хранить под замком. Подробнее об опасности таких лекарств — в статье про [зависимость от снотворных и успокоительных](/articles/zavisimost-ot-snotvornyh-i-uspokoitelnyh).
:::

## Учёба и цифровые следы

Падение успеваемости, прогулы, жалобы учителей часто становятся первым сигналом. В телефоне и соцсетях насторожат сленговые слова о веществах, странные переводы денег, чаты с незнакомыми людьми, ролики с «челленджами» и хвастовством употреблением. Подростки всё чаще делятся опытом в Сети — и именно там узнают о новых опасных способах. Если ребёнок почти не выпускает телефон, прочитайте также про [интернет-зависимость у подростка](/articles/internet-zavisimost-u-podrostka).

