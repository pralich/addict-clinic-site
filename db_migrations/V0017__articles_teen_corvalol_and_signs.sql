## Почему важно заметить рано

Мозг подростка продолжает развиваться примерно до 25 лет. Любые вещества — алкоголь, наркотики, лекарства, энергетики в больших дозах — вмешиваются в этот процесс и сильнее бьют по памяти, вниманию и эмоциям. Кроме того, подростки чаще экспериментируют с опасными сочетаниями, не понимая последствий. Свежий пример — [коктейли из корвалола и энергетиков](/articles/reabilitatsiya-podrostkov-korvalol-i-energetiki), которые школьники пробуют ради «кайфа».

## Изменения в поведении

- **Резкая смена компании** — старые друзья пропали, новых вы не знаете и с ними не знакомят
- **Скрытность** — пароли на всём, разговоры шёпотом, вранье о том, где был
- **Перепады настроения** — эйфория и болтливость сменяются апатией, раздражительностью, агрессией
- **Потеря интересов** — бросил секцию, хобби, перестал общаться с семьёй
- **Нарушения сна** — не спит ночами или спит днём по 12–14 часов
- **Деньги** — постоянно просит, продаёт вещи, из дома пропадают деньги и ценности

