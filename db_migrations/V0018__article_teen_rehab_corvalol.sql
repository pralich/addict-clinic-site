## Профилактика: что сделать родителям уже сегодня

1. Проверьте домашнюю аптечку и уберите под замок препараты с фенобарбиталом, снотворные и сильные успокоительные.
2. Поговорите с ребёнком о тренде спокойно, без обвинений: спросите, слышал ли он о нём и что думает.
3. Объясните реальные последствия — аритмию, разрушение печени, потерю сознания, а не «это плохо».
4. Интересуйтесь его жизнью, друзьями и тем, что он смотрит в Сети.
5. Обратите внимание на тревогу, стресс и проблемы в школе — часто именно они толкают к веществам.
6. При первых подозрениях обратитесь к специалисту — консультация для родителей анонимна.

