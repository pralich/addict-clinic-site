## Что происходит: тренд из соцсетей

Подростки ищут доступный способ изменить состояние — без дилеров и риска «попасться». Корвалол кажется безобидным: это «лекарство бабушек», его можно найти в домашней аптечке. Энергетики продаются на каждом углу. Ролики и посты о «коктейле» распространяются среди школьников быстрее, чем родители успевают о нём узнать.

:::callout warning
То, что лекарство продаётся в аптеке, не делает его безопасным. Корвалол рассчитан на взрослых в небольших дозах — а подростки пьют его флаконами и смешивают со стимуляторами.
:::

## Чем опасен корвалол

В состав корвалола входит **фенобарбитал** — препарат из группы барбитуратов. Он угнетает центральную нервную систему: замедляет реакцию, мышление и речь, вызывает сонливость и заторможенность. Кроме того, в каплях есть бромсодержащее вещество и спиртовая основа.

- **Привыкание.** Фенобарбитал вызывает физическую и психическую зависимость. Чтобы получить прежний эффект, нужны всё большие дозы.
- **Отравление бромом.** При частом приёме бром накапливается в организме: появляются вялость, нарушения координации, кожная сыпь, проблемы с памятью.
- **Угнетение дыхания.** В больших дозах барбитураты подавляют дыхательный центр — это смертельно опасно.
- **Удар по развивающемуся мозгу.** У подростков страдают внимание, память, способность к учёбе и контролю эмоций.

## Почему смесь с энергетиком особенно опасна

Энергетик содержит большие дозы кофеина и других стимуляторов. Получается, что одно вещество тормозит нервную систему, а другое — разгоняет сердце. Организм оказывается между двух огней.

| Что происходит | Последствия |
|---|---|
| Сердце работает на износ | Тахикардия, аритмия, скачки давления |
| Печень перерабатывает два токсичных вещества сразу | Токсическое поражение печени вплоть до её разрушения |
| Стимулятор маскирует действие барбитурата | Подросток не чувствует опьянения и пьёт больше |
| Эффект кофеина проходит быстрее | Резкое угнетение сознания, вплоть до его потери |
| Нервная система получает противоположные сигналы | Тревога, панические атаки, бессонница, судороги |

:::callout info
Самое коварное — эффект маскировки. Пока действует энергетик, подросток чувствует себя бодрым и думает, что «ничего не будет». Когда кофеин перестаёт действовать, фенобарбитал продолжает работать в полную силу.
:::

