### Почему важно не тянуть

У подростков зависимость формируется быстрее, чем у взрослых, а последствия для мозга сохраняются дольше. Ранняя помощь — это обычно короткая программа и полное восстановление. Помощь «когда уже совсем плохо» — длительная реабилитация и лечение печени и сердца.

