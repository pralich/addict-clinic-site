## Срочная помощь: когда звонить 103 или 112

Немедленно вызывайте скорую, если подросток не просыпается или с трудом приходит в себя, дышит редко и поверхностно, жалуется на боль в груди и перебои в сердце, у него судороги, синеют губы. До приезда врачей положите его на бок, не оставляйте одного, не давайте «отпаивать» кофе или другими энергетиками. Сообщите врачам, что и в каком количестве он мог выпить, — сохраните флаконы.

## Реабилитация подростков: чем она отличается

Даже если употребление было «пару раз», важно разобраться, почему подросток к нему пришёл. За тягой к веществам почти всегда стоят тревога, конфликты, давление сверстников, одиночество или неумение справляться со стрессом. Реабилитация подростков работает именно с этими причинами — и всегда вовлекает семью.

