## Почему алкоголик не хочет лечиться

Алкоголизм поражает ту часть мозга, которая отвечает за критику к себе. Поэтому отрицание — симптом болезни, а не упрямство. Кроме того, человек может бояться кодирования, огласки, «психушки» или просто не верить, что жизнь без алкоголя бывает хорошей.

