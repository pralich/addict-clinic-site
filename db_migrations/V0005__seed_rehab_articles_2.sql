## От чего зависит стоимость

| Фактор | Как влияет |
|---|---|
| Длительность программы | Основной фактор: 28, 45, 60 или 90 дней |
| Медицинская составляющая | Детокс, психиатр, анализы, препараты |
| Условия проживания | Количество человек в комнате, питание, территория |
| Количество специалистов | Индивидуальные сессии против только групповых |
| Работа с семьёй | Семейные консультации, группы для близких |
| Постреабилитация | Сопровождение после выписки |

