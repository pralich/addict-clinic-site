## Условия проживания в нашем центре

- **Комнаты на 1–2 человека** с собственным санузлом.
- **Пятиразовое питание** — меню составляет диетолог.
- **Загородная территория** в сосновом лесу: прогулки, спортплощадка, тренажёрный зал.
- **Круглосуточный медицинский пост**.
- **Связь с близкими** по согласованному графику.

Для тех, кому важны максимальный комфорт и анонимность — программа [PREMIUM](/premium) с отдельными люксами, SPA и личным куратором.

