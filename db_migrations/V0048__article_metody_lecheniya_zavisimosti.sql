## Почему не бывает одного «правильного» метода

Зависимость формируется на нескольких уровнях одновременно. На биологическом — меняется работа системы вознаграждения мозга, появляются толерантность и синдром отмены. На психологическом — вещество или игра становятся главным способом справляться с тревогой, болью, скукой или одиночеством. На социальном — рушатся отношения, работа, привычный круг общения, а вокруг остаются те, кто употребляет.

Метод, который влияет только на один уровень, почти всегда даёт временный результат. Капельница снимет ломку, но не уберёт тягу. Кодирование на время остановит употребление, но не научит жить без алкоголя. Разговор с психологом не поможет, пока человек в тяжёлой абстиненции. Поэтому современная наркология опирается на **биопсихосоциальный подход**: лечить нужно и тело, и психику, и окружение.

:::callout info
Эффективное лечение — это не выбор между «капельницей», «психологом» и «реабилитацией», а их правильная последовательность и сочетание под конкретного человека.
:::

## Детоксикация: первый медицинский этап

**Детоксикация** — это очищение организма от вещества и безопасное прохождение синдрома отмены. Без неё человек физически не способен включиться в психотерапию: его мысли заняты ломкой, бессонницей, тревогой и тягой.

### Как проходит детокс

- **Капельницы и инфузионная терапия** — восстанавливают водно-солевой баланс, выводят токсины, поддерживают печень, сердце и нервную систему.
- **Медикаментозное снятие абстиненции** — препараты подбираются под вещество: при алкоголе, опиоидах, стимуляторах, снотворных схемы принципиально разные.
- **Контроль жизненных показателей** — давление, пульс, сатурация, работа сердца. Особенно важно при длительных запоях и отмене транквилизаторов, где возможны судороги и психозы.
- **Восстановление сна и питания** — без этого организм не выходит из состояния стресса.

### Где проводить детокс

| Формат | Кому подходит | Ограничения |
|---|---|---|
| Выезд нарколога на дом | Короткий запой, стабильное состояние, нет тяжёлых хронических болезней | Нет круглосуточного наблюдения |
| Стационар клиники | Длительное употребление, опиоиды, транквилизаторы, риск судорог и психоза, сопутствующие болезни | Нужно несколько дней провести в клинике |
| Дневной стационар | Лёгкая абстиненция, высокая мотивация, поддержка семьи | Требует ежедневных визитов |

:::callout warning
Резкий самостоятельный отказ от алкоголя после долгого запоя или от снотворных и успокоительных может быть опасен для жизни: возможны судороги и алкогольный делирий («белая горячка»). Отмену таких веществ должен контролировать врач.
:::

Подробнее о домашнем формате — в статье [вывод из запоя на дому](/articles/vyvod-iz-zapoya-na-domu), а об опасной отмене таблеток — в материале про [зависимость от снотворных и успокоительных](/articles/zavisimost-ot-snotvornyh-i-uspokoitelnyh).

### Чего детокс не делает

Детокс устраняет физическую зависимость, но **не лечит саму болезнь**. Психологическая тяга, привычные сценарии, триггеры и окружение остаются. Если после капельниц человек возвращается в прежнюю жизнь без дальнейшей помощи, срыв почти неизбежен. Детокс — это вход в лечение, а не его финал.

## Наркологическая клиника: медицина и безопасность

**Наркологическая клиника** — медицинское учреждение с лицензией, врачами и стационаром. Здесь проводят детоксикацию, диагностику, лечат осложнения и сопутствующие заболевания, подбирают медикаментозную поддержку.

### Что даёт клиника

- круглосуточное наблюдение врачей и медсестёр
- лабораторную и инструментальную диагностику: анализы, ЭКГ, УЗИ, консультации профильных специалистов
- лечение последствий употребления — поражения печени, сердца, нервной системы, психических расстройств
- безопасную среду без доступа к веществу в самый уязвимый период
- возможность сразу перейти к психотерапии и реабилитации

### Чем клиника отличается от реабилитационного центра

Клиника отвечает за **медицинскую часть** — тело и острые психические состояния. Реабилитационный центр — за **восстановление личности и навыков жизни без вещества**. Идеально, когда оба этапа связаны: человек переходит из стационара в реабилитацию без «разрыва», в котором чаще всего и случаются срывы.

## Медикаментозные методы

Лекарства в наркологии решают три задачи: снять острое состояние, вылечить сопутствующие расстройства и снизить риск возврата к употреблению.

### Препараты для снятия абстиненции

Подбираются врачом под конкретное вещество и состояние: успокоительные и противосудорожные средства под контролем, витамины группы B, гепатопротекторы, препараты для сна и снижения тревоги. Самолечение здесь опасно — многие из этих средств сами по себе вызывают зависимость.

### Препараты против тяги и рецидива

- **Блокаторы опиоидных рецепторов** (налтрексон в таблетках или в форме длительного действия) — снижают эйфорию от алкоголя и опиоидов и уменьшают тягу.
- **Сенсибилизирующая терапия** (дисульфирам) — вызывает тяжёлую реакцию при приёме алкоголя. Работает за счёт страха, поэтому без психотерапии эффект обычно временный.
- **Антидепрессанты, нормотимики, противотревожные средства** — назначаются психиатром, если зависимость сочетается с депрессией, тревожным или биполярным расстройством.

### Что такое «кодирование»

Под словом «кодирование» в России объединяют очень разные методы: от введения препаратов длительного действия до психотерапевтических внушений. Важно понимать: любое кодирование — это **запрет, а не лечение причины**. Оно может дать время на восстановление, но если в этот период не работать с психикой, человек часто срывается сразу после окончания срока. Подробно об этом — в статье [почему кодирования недостаточно](/articles/reabilitatsiya-alkogolikov).

:::callout info
В России запрещена заместительная терапия опиоидной зависимости метадоном и бупренорфином, которая применяется во многих странах. Поэтому отечественная наркология делает ставку на детокс, блокаторы рецепторов, психотерапию и реабилитацию.
:::

## Работа с психологом и психотерапевтом

Психотерапия — сердце лечения зависимости. Именно она отвечает на вопросы «почему я употребляю» и «как жить по-другому».

### Основные подходы

- **Когнитивно-поведенческая терапия (КПТ)** — один из методов с самой сильной доказательной базой. Учит распознавать триггеры, автоматические мысли, ведущие к употреблению, и заменять их новыми реакциями.
- **Мотивационное интервьюирование** — помогает человеку самому найти причины измениться, а не сопротивляться давлению. Особенно полезно, когда мотивации к лечению пока мало.
- **Профилактика рецидива** — план действий на случай тяги, стресса и опасных ситуаций.
- **Диалектическая поведенческая терапия (ДБТ)** — работа с сильными эмоциями и импульсивностью, помогает при сочетании зависимости с расстройствами личности.
- **Психодинамическая и экзистенциальная терапия** — исследование глубинных причин: травм, утрат, пустоты, отсутствия смысла.
- **Групповая терапия** — опыт других людей, обратная связь и ощущение, что ты не один.
- **Семейная терапия** — восстановление отношений и изменение правил в семье, которые поддерживали болезнь.

### Психолог или психотерапевт

**Психолог** работает с мышлением, эмоциями и поведением, но не назначает лекарств. **Психотерапевт** — врач с медицинским образованием, который может сочетать терапию с медикаментами. В хорошей команде они работают вместе с наркологом и психиатром.

## Реабилитационный центр

**Реабилитация** — этап, на котором человек учится жить трезво: справляться с эмоциями без вещества, выстраивать отношения, распорядок, ответственность. Это длительная работа — обычно от нескольких недель до нескольких месяцев.

### Форматы реабилитации

| Формат | Суть | Кому подходит |
|---|---|---|
| Стационарный центр | Проживание в центре, программа на каждый день, изоляция от триггеров | Тяжёлая зависимость, срывы в анамнезе, неблагоприятное окружение |
| Амбулаторная программа | Терапия и группы несколько раз в неделю без отрыва от работы и семьи | Высокая мотивация, стабильное окружение, лёгкая или средняя стадия |
| Ресоциализация | Постепенное возвращение к работе, учёбе, самостоятельной жизни при поддержке специалистов | После стационарной реабилитации |
| Частная резиденция | Индивидуальная программа в условиях полной конфиденциальности | Тем, для кого особенно важны закрытость и комфорт |

