Специалисты addict.clinic работают в этой сфере десятки лет и видели, как меняется сама зависимость и то, как люди её отрицают. Это опыт, который нельзя получить из учебника.

| Поколение | Чем чаще злоупотребляют | Как звучит отрицание |
|---|---|---|
| Старшее поколение | Алкоголь, снотворные, обезболивающие | «Мы всю жизнь так жили», «Это лекарство, мне врач выписал» |
| Средний возраст | Алкоголь, стимуляторы, азартные игры | «Я работаю и обеспечиваю семью — значит, всё нормально» |
