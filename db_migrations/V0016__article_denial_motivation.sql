У каждого возраста свои аргументы, свои страхи и свой язык. Подход, который сработает с пятидесятилетним отцом, не подойдёт двадцатилетнему сыну. Наши психологи знают эти различия и подбирают слова под конкретного человека.

## Ошибки, которые совершают родственники

Близкие действуют из любви и отчаяния, но некоторые шаги только отдаляют лечение:

:::checklist
Читать нотации и стыдить — это усиливает защиту
Говорить с человеком в состоянии опьянения
Угрожать и не выполнять угроз
Покрывать: звонить на работу, отдавать долги, врать окружающим
Обманом везти «к врачу» без подготовки
Ждать, что человек «сам дойдёт до дна»
:::

:::callout warning
Ожидание «дна» опасно: для кого-то им становится тяжёлая болезнь, авария или передозировка. Действовать нужно раньше.
:::

