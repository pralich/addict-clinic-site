## Почему зависимый не видит проблему

Отрицание — это не вредность и не «плохой характер». Это защитный механизм психики и один из ключевых симптомов самой болезни. Признать зависимость — значит признать, что жизнь вышла из-под контроля, а это больно и страшно. Поэтому психика выстраивает оборону:

- **Преуменьшение** — «я пью только по выходным», «это всего лишь трава»
- **Сравнение** — «вот сосед действительно спился, а я нет»
- **Перекладывание вины** — «я пью, потому что ты меня пилишь», «на работе стресс»
- **Рационализация** — «мне нужно расслабиться, у меня тяжёлая жизнь»
- **Агрессия** — любая попытка поговорить заканчивается скандалом

Чем дольше длится употребление, тем крепче эта оборона. Именно поэтому уговоры, слёзы и ультиматумы родственников чаще всего не работают — а иногда только усиливают сопротивление.

:::callout info
Отрицание не означает, что человек «не хочет жить нормально». Внутри почти всегда есть сомнения, страх и стыд. Задача специалиста — найти эту часть личности и опереться на неё.
:::

