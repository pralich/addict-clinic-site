## Что такое реабилитационный центр

Реабилитационный центр — это учреждение, где зависимый человек после детоксикации проходит восстановление: работает с психологами, учится жить без алкоголя или наркотиков, восстанавливает отношения и навыки. В отличие от наркологического стационара, где снимают острое состояние, центр реабилитации работает с причинами зависимости.

| Этап | Где проходит | Задача |
|---|---|---|
| Детоксикация | Наркологический стационар | Очистить организм, снять ломку или абстиненцию |
| Реабилитация | Реабилитационный центр | Изменить мышление и поведение, научиться жить трезво |
| Ресоциализация | Амбулаторно / центр | Вернуться к работе, семье, обычной жизни |

