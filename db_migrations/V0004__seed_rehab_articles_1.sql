## Почему детокса недостаточно

Детоксикация убирает вещество из организма и снимает физическую ломку. Но остаётся:

- **Психологическая тяга** — мозг помнит удовольствие и ищет его снова.
- **Триггеры** — места, люди, эмоции, связанные с употреблением.
- **Постабстинентный синдром** — недели и месяцы перепадов настроения, бессонницы, апатии.
- **Разрушенные навыки** — умение справляться со стрессом, общаться, работать.

Реабилитация работает именно с этим.

